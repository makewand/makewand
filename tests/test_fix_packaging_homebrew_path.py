"""
arch-5: the Homebrew wrapper generated by scripts/gen_package_manifests.sh must
use the caller's PATH at run time.

The formula used to write ``PATH="<python>/bin:#{ENV["PATH"]}"`` into
bin/makewand, freezing brew's sanitized build-time PATH (superenv shims, no
~/.local/bin, npm globals, HOMEBREW_PREFIX/bin or /usr/local/bin), so provider
CLIs were not found when makewand ran.
"""

try:  # 测试隔离必须先于 makewand 导入：临时 HOME/配置、AI CLI 桩、屏蔽本地模型端点
    import _isolation  # noqa: F401
except ImportError:  # python3 -m unittest tests.<module>
    from tests import _isolation  # noqa: F401

import os
import re
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
GENERATOR = REPO_ROOT / "scripts" / "gen_package_manifests.sh"
VERSION = "1.2.3"
# A PATH entry only the generator process sees: it must never reach the formula.
GENERATOR_MARKER_DIR = "/nonexistent-makewand-generator-marker/bin"
# Any ENV access in `def install` (ENV["PATH"], ENV['PATH'], ENV.fetch, ENV.to_h,
# ...) reads brew's sanitized build-time environment, which the wrapper would freeze.
BUILD_TIME_ENV_USE = re.compile(r"\bENV\s*[\[.]")
WRAPPER_PATH_LINE = re.compile(r'write_env_script libexec/"makewand", PATH: "(.*)"$', re.M)


def build_time_env_uses(install_body):
    """ENV accesses in the code of a formula's install block (full-line comments ignored)."""
    code = "\n".join(line for line in install_body.splitlines() if not re.match(r"\s*#(?!\{)", line))
    return BUILD_TIME_ENV_USE.findall(code)

# Runs the generated formula's own `def install` with minimal Homebrew stubs.
# install and write_env_script follow Homebrew's Library/Homebrew/extend/pathname.rb.
SIM_BREW_INSTALL = r'''
require "pathname"
require "fileutils"

formula_path, prefix, bundle_dir, install_path = ARGV
PREFIX = Pathname(prefix).expand_path

class Pathname
  def install(*sources)
    mkpath
    sources.flatten.each { |src| FileUtils.cp_r(src.to_s, join(Pathname(src).basename).to_s) }
  end

  def write_env_script(target, args_or_env, env = nil)
    args = if env.nil?
      env = args_or_env
      nil
    elsif args_or_env.is_a?(Array)
      args_or_env.join(" ")
    else
      args_or_env
    end
    env_export = +""
    env.each { |key, value| env_export << "#{key}=\"#{value}\" " }
    dirname.mkpath
    write <<~SH
      #!/bin/bash
      #{env_export}exec "#{target}" #{args} "$@"
    SH
    chmod 0555
  end
end

module Hardware
  module CPU
    def self.arm?
      false
    end
  end
end

class Formula
  Dep = Struct.new(:opt_bin, :opt_libexec)
  def self.[](name)
    Dep.new(PREFIX/"opt"/name/"bin", PREFIX/"opt"/name/"libexec")
  end
  %i[desc homepage version license depends_on url sha256].each { |m| define_singleton_method(m) { |*| nil } }
  def self.on_macos(&block); end
  def self.on_linux(&block); end
  def self.test(&block); end
  def keg
    PREFIX/"Cellar/makewand/1.2.3"
  end
  def bin
    keg/"bin"
  end
  def libexec
    keg/"libexec"
  end
end

load formula_path
ENV["PATH"] = install_path # superenv's sanitized build PATH during `def install`
Dir.chdir(bundle_dir) { Makewand.new.install }
'''


def _bash():
    return shutil.which("bash")


@unittest.skipIf(sys.platform == "win32" or _bash() is None, "the generator is a bash script")
class HomebrewWrapperPathTests(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="mw-brew-path-"))
        self.addCleanup(shutil.rmtree, self.tmp, ignore_errors=True)
        self.formula = self._generate()

    def _generate(self) -> Path:
        checksums = self.tmp / "checksums.txt"
        lines = [f"{'1' * 64}  makewand_v{VERSION}_{target}.tar.gz"
                 for target in ("linux_amd64", "linux_arm64", "darwin_amd64", "darwin_arm64")]
        lines.append(f"{'2' * 64}  makewand_v{VERSION}_windows_amd64.zip")
        checksums.write_text("\n".join(lines) + "\n")
        env = dict(os.environ)
        env["PATH"] = GENERATOR_MARKER_DIR + os.pathsep + env.get("PATH", "/usr/bin:/bin")
        subprocess.run([_bash(), str(GENERATOR), f"v{VERSION}", "owner/repo", str(checksums), str(self.tmp / "dist")],
                       check=True, env=env, capture_output=True, text=True)
        return self.tmp / "dist" / "homebrew" / "Formula" / "makewand.rb"

    def _install_body(self, text):
        install = re.search(r"def install\n(.*?)\n  end\n", text, re.S)
        self.assertIsNotNone(install, text)
        return install.group(1)

    def test_formula_embeds_no_install_time_path(self):
        text = self.formula.read_text()
        body = self._install_body(text)
        self.assertEqual(build_time_env_uses(body), [], "the wrapper must not freeze brew's build-time PATH")
        self.assertNotIn(GENERATOR_MARKER_DIR, text, "the generator's own PATH leaked into the formula")
        match = WRAPPER_PATH_LINE.search(body)
        self.assertIsNotNone(match, body)
        value = match.group(1)
        self.assertTrue(value.startswith('#{Formula["python@3.12"].opt_libexec}/bin'), value)
        self.assertIn("$PATH", value, "the wrapper must expand the caller's PATH at run time")

    def test_static_check_rejects_a_wrapper_that_also_embeds_the_build_time_path(self):
        # Without ruby only the static check runs: it must catch a hybrid that keeps
        # the run-time ${PATH:+:$PATH} but appends brew's build-time PATH anyway.
        body = self._install_body(self.formula.read_text())
        value = WRAPPER_PATH_LINE.search(body).group(1)
        for frozen in ("#{ENV['PATH']}", '#{ENV["PATH"]}', '#{ENV.fetch("PATH")}', "#{ENV.fetch('PATH', '')}",
                       "#{ENV [ 'PATH' ]}", "#{ENV.to_h['PATH']}"):
            with self.subTest(frozen=frozen):
                hybrid = body.replace(value, value + ":" + frozen)
                self.assertNotEqual(hybrid, body)
                self.assertNotEqual(build_time_env_uses(hybrid), [], hybrid)
        commented = "    # never write ENV[\"PATH\"] into the wrapper\n" + body
        self.assertEqual(build_time_env_uses(commented), [])

    @unittest.skipIf(shutil.which("ruby") is None, "ruby is needed to run the formula's install method")
    def test_installed_wrapper_uses_the_callers_runtime_path(self):
        prefix = self.tmp / "prefix"
        bundle = self.tmp / "bundle"
        (bundle / "lib").mkdir(parents=True)
        (bundle / "makewand").write_text('#!/bin/sh\nprintf "%s" "$PATH"\n')
        (bundle / "makewand").chmod(0o755)
        sim = self.tmp / "sim_brew_install.rb"
        sim.write_text(SIM_BREW_INSTALL)
        shims = prefix / "Library/Homebrew/shims/linux/super/bin"
        install_path = os.pathsep.join([str(shims), str(prefix / "opt/python@3.12/bin"), "/usr/bin", "/bin"])
        subprocess.run(["ruby", str(sim), str(self.formula), str(prefix), str(bundle), install_path],
                       check=True, capture_output=True, text=True)
        wrapper = prefix / "Cellar/makewand/1.2.3/bin/makewand"
        engine_python = str(prefix / "opt/python@3.12/libexec/bin")

        user_path = os.pathsep.join([str(self.tmp / "home/.local/bin"), str(self.tmp / "home/.npm-global/bin"),
                                     str(prefix / "bin"), "/usr/local/bin", "/usr/bin", "/bin"])
        seen = subprocess.run([str(wrapper)], env={"PATH": user_path}, check=True,
                              capture_output=True, text=True).stdout
        self.assertEqual(seen, engine_python + os.pathsep + user_path)
        self.assertNotIn(str(shims), seen, "brew's build-time shims must not reach the runtime PATH")

        # A run with the user's PATH changed after installation sees the change.
        later = str(self.tmp / "installed-later/bin") + os.pathsep + user_path
        seen = subprocess.run([str(wrapper)], env={"PATH": later}, check=True, capture_output=True, text=True).stdout
        self.assertEqual(seen, engine_python + os.pathsep + later)

        # An empty PATH must not become a current-directory ("") entry.
        seen = subprocess.run([str(wrapper)], env={"PATH": ""}, check=True, capture_output=True, text=True).stdout
        self.assertEqual(seen, engine_python)


if __name__ == "__main__":
    unittest.main()
